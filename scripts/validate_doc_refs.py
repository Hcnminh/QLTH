#!/usr/bin/env python3
"""Validate documentation references (images and anchor links) in docs/.

Checks performed:
  1. All image references ![alt](path) in docs/*.md resolve to existing, non-empty files.
  2. All internal section anchor links [text](#anchor) resolve to existing headings (verified with pandoc HTML heading IDs).
  3. Validates required user manual docs/huong-dan-su-dung.md existence and structural sections.

Exit code 0 = pass, 1 = fail with printed diagnostics.
Usage:
    python3 scripts/validate_doc_refs.py
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = REPO_ROOT / "docs"

errors: list[str] = []
warnings: list[str] = []


def fail(msg: str) -> None:
    errors.append(msg)


def warn(msg: str) -> None:
    warnings.append(msg)


def extract_pandoc_heading_ids(file_path: Path) -> set[str]:
    """Run pandoc to get exact heading IDs generated by standard markdown parser."""
    try:
        proc = subprocess.run(
            ["pandoc", str(file_path), "-f", "gfm", "-t", "html5"],
            capture_output=True,
            text=True,
            cwd=str(file_path.parent),
            check=True,
        )
        # Find all id="..." in heading tags
        heading_ids = set(re.findall(r"<h[1-6]\s+[^>]*id=[\"']([^\"']+)[\"']", proc.stdout))
        return heading_ids
    except Exception as e:
        warn(f"Could not extract heading IDs with pandoc: {e}")
        return set()


def validate_markdown_file(file_path: Path) -> None:
    if not file_path.exists():
        fail(f"Required document not found: {file_path}")
        return

    content = file_path.read_text(encoding="utf-8")
    lines = content.splitlines()

    pandoc_ids = extract_pandoc_heading_ids(file_path)

    # 1. Check image references ![alt](image_path)
    image_pattern = re.compile(r"!\[(.*?)\]\((.*?)\)")
    for line_num, line in enumerate(lines, 1):
        for alt, img_path in image_pattern.findall(line):
            # Strip title if present: ![alt](path "title")
            img_clean_path = img_path.split()[0].strip()
            # If path contains query or hash, strip it
            img_clean_path = img_clean_path.split("?")[0].split("#")[0]
            
            resolved_path = (file_path.parent / img_clean_path).resolve()
            if not resolved_path.exists():
                fail(f"{file_path.name}:{line_num}: Broken image reference '{img_clean_path}' -> {resolved_path}")
            elif resolved_path.stat().st_size == 0:
                fail(f"{file_path.name}:{line_num}: Image file is empty '{img_clean_path}'")

    # 2. Check internal anchor links [text](#anchor)
    anchor_pattern = re.compile(r"\[(.*?)\]\(#([a-zA-Z0-9_\-\u00C0-\u1EF9]+)\)")
    for line_num, line in enumerate(lines, 1):
        for link_text, anchor in anchor_pattern.findall(line):
            if pandoc_ids and anchor not in pandoc_ids:
                # Check case-insensitivity or minor difference
                matched = any(anchor.lower() == pid.lower() for pid in pandoc_ids)
                if not matched:
                    fail(f"{file_path.name}:{line_num}: Unresolved internal anchor link '#{anchor}'")


def validate_brochures() -> None:
    docx_path = DOCS_DIR / "brochure-qlth-kpi.docx"
    pdf_path = DOCS_DIR / "brochure-qlth-kpi.pdf"

    if not docx_path.exists():
        fail(f"Required brochure Word document not found: {docx_path}")
    elif docx_path.stat().st_size < 50 * 1024:
        fail(f"Brochure Word document is too small ({docx_path.stat().st_size} bytes, expected > 50KB)")
    else:
        print(f"  - Verified {docx_path.name}: {docx_path.stat().st_size:,} bytes (> 50KB)")

    if not pdf_path.exists():
        fail(f"Required brochure PDF document not found: {pdf_path}")
    elif pdf_path.stat().st_size < 50 * 1024:
        fail(f"Brochure PDF document is too small ({pdf_path.stat().st_size} bytes, expected > 50KB)")
    else:
        print(f"  - Verified {pdf_path.name}: {pdf_path.stat().st_size:,} bytes (> 50KB)")


def main() -> int:
    manual_path = DOCS_DIR / "huong-dan-su-dung.md"
    if not manual_path.exists():
        fail(f"Primary manual does not exist: {manual_path}")
    else:
        validate_markdown_file(manual_path)

    validate_brochures()

    print(f"Validated documentation references in {manual_path.name} & collateral brochures:")
    print(f"  - Status: {'FAILED' if errors else 'PASSED'}")
    print(f"  - Errors: {len(errors)}")
    print(f"  - Warnings: {len(warnings)}")

    if warnings:
        for w in warnings:
            print(f"  [WARN] {w}")

    if errors:
        for err in errors:
            print(f"  [ERROR] {err}", file=sys.stderr)
        return 1

    print("All image and section references in documentation are verified OK.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
